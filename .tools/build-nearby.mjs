/**
 * Build public/data/nearby.json — the three necessities a person asks about at
 * the worst moment: a pharmacy, a hospital, a doctor.
 *
 * It is cut from the same local OpenStreetMap dump as the open-records tier, so
 * it carries that dump's retrieval date and nothing else. It is deliberately
 * small and flat: the browser loads it once when somebody opens the "around
 * here" panel, then answers every distance locally. What the dump does not
 * contain is left out here too — there are no ATMs in it, so the file has no
 * ATMs, and the panel says so rather than showing an empty category.
 *
 * Usage: node .tools/build-nearby.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'Karachify Research/data/by-category';
const OUT = 'public/data/nearby.json';

/** The categories worth asking about at an emergency, and what each becomes. */
const KINDS = {
  'pharmacies-labs': 'pharmacy',
  hospitals: 'hospital',
  'doctors-clinics': 'clinic',
};

const failures = [];
const records = [];
const retrievedDates = new Set();

for (const [file, kind] of Object.entries(KINDS)) {
  const at = join(SRC, `${file}.json`);
  if (!existsSync(at)) {
    failures.push(`${file}: the research dump is missing`);
    continue;
  }
  const rows = JSON.parse(readFileSync(at, 'utf8'));
  for (const r of rows) {
    if (!Number.isFinite(r.lat) || !Number.isFinite(r.lng)) {
      failures.push(`${r.slug}: coordinates ${r.lat}/${r.lng}`);
      continue;
    }
    if (Math.abs(r.lat - 24.86) > 1.2 || Math.abs(r.lng - 67.01) > 1.2) {
      failures.push(`${r.slug}: ${r.lat},${r.lng} is not Karachi`);
      continue;
    }
    const osm = typeof r.sourceUrl === 'string' ? r.sourceUrl.replace(/^https?:\/\/www\.openstreetmap\.org\//, '') : null;
    if (!osm || !/^(node|way|relation)\/\d+$/.test(osm)) {
      failures.push(`${r.slug}: no OpenStreetMap element behind it (${r.sourceUrl})`);
      continue;
    }
    const row = { name: r.name, kind, lat: r.lat, lng: r.lng, areaId: r.areaId, osm };
    if (r.phone) row.phone = r.phone;
    if (r.research?.sources?.[0]?.retrievedAt) retrievedDates.add(r.research.sources[0].retrievedAt);
    records.push(row);
  }
}

if (failures.length) {
  console.error('Nearby build failed:');
  for (const f of failures.slice(0, 20)) console.error('  - ' + f);
  if (failures.length > 20) console.error(`  … and ${failures.length - 20} more`);
  process.exit(1);
}

if (retrievedDates.size !== 1) failures.push(`the dump does not agree on one retrieval date: ${[...retrievedDates].join(', ') || 'none'}`);
if (!retrievedDates.size) {
  console.error('Nearby build failed: no record carries a retrieval date, so the panel could not say when it was read.');
  process.exit(1);
}

records.sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name));

const out = {
  note: 'Generated by .tools/build-nearby.mjs from the local OpenStreetMap research dump. Do not edit by hand.',
  licence: 'OpenStreetMap contributors, ODbL 1.0',
  retrievedAt: [...retrievedDates][0],
  kinds: Object.values(KINDS),
  /** The dump has no ATMs, banks or fuel pumps, so none are claimed here. */
  notCovered: ['atm'],
  total: records.length,
  records,
};

/* Written compact: the browser reads it, nobody diffs it by hand, and every
   kilobyte here is paid for by whoever opens the panel. */
const text = JSON.stringify(out);
writeFileSync(OUT, text, 'utf8');
const counts = records.reduce((m, r) => ({ ...m, [r.kind]: (m[r.kind] || 0) + 1 }), {});
console.log(
  `✓ nearby: ${records.length} records (${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}) read ${out.retrievedAt} · ${(
    text.length / 1024
  ).toFixed(0)} KB`,
);
