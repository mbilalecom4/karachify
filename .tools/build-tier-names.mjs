/**
 * Writes public/data/tier/names.json — the three fields search needs from every
 * record in the open tier, and nothing else.
 *
 * The tier JSON a category page reads is 7.5 MB, because each record carries an
 * address, coordinates, tags and hours. A visitor typing in the search box has
 * earned none of that, so this file keeps only what a result row can show:
 * slug, name and area. It is derived from the committed part files, so it can
 * only ever list the records the site already publishes — check-data.mjs
 * compares the two on every build and fails if they drift.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tierDir = join(root, 'public', 'data', 'tier');
const out = join(tierDir, 'names.json');

const fail = (msg) => {
  console.error(`✗ build-tier-names: ${msg}`);
  process.exit(1);
};

const summary = JSON.parse(readFileSync(join(tierDir, 'index.json'), 'utf8'));
const byCategory = {};
let total = 0;

for (const category of summary.categories) {
  const manifestPath = join(tierDir, 'parts', `${category.id}.json`);
  if (!existsSync(manifestPath)) fail(`no part manifest for category ${category.id}`);
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const rows = [];
  /* The manifest lists ranges (from/to/n), the reader asks for NNN.json in
     order, and the files on disk are exactly that — so the position in the
     manifest is the file name. */
  for (let position = 0; position < manifest.parts.length; position++) {
    const name = `${String(position + 1).padStart(3, '0')}.json`;
    const file = join(tierDir, 'parts', category.id, name);
    if (!existsSync(file)) fail(`manifest for ${category.id} has a part ${position + 1} that is not on disk`);
    const part = JSON.parse(readFileSync(file, 'utf8'));
    for (const r of part.records) rows.push([r.slug, r.name, r.areaId]);
  }
  if (rows.length !== category.count) {
    fail(`${category.id}: the manifest says ${category.count} records, the parts hold ${rows.length}`);
  }
  byCategory[category.id] = rows;
  total += rows.length;
}

if (total !== summary.total) fail(`collected ${total} records, the summary declares ${summary.total}`);

const json = `${JSON.stringify({
  note: 'Generated by .tools/build-tier-names.mjs from the tier part files. Search reads only this file, so a query never pulls the 7.5 MB a category page needs. Do not edit by hand.',
  licence: summary.licence,
  retrievedAt: summary.retrievedAt,
  total,
  byCategory,
})}\n`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, json);
console.log(`✓ build-tier-names: ${total} names across ${Object.keys(byCategory).length} categories, ${(json.length / 1024).toFixed(0)} kB`);
